  describe "G1 subgroup check" do
    # E(Fp) has order h·r with cofactor h = (x − 1)²/3 = 3 · 11² · 10177² ·
    # 859267² · 52437899². The endomorphism test accepts exactly the kernel of
    # a group endomorphism, so it is sound if it rejects every point of prime
    # order ℓ dividing h. These tests reject one such point per ℓ; Dai et al.
    # (eprint 2022/352) prove the test for BLS12-381.
    @cofactor 0x396C8C005555E1568C00AAAB0000AAAB

    test "the cofactor factors as stated" do
      assert 3 * Integer.pow(11 * 10_177 * 859_267 * 52_437_899, 2) == @cofactor
    end

    test "accepts the generator and its multiples" do
      g = Curve.g1_generator()
      assert Curve.in_subgroup?(g)
      assert Curve.in_subgroup?(Curve.msm([{g, 0xDEADBEEF}]))
    end

    for {prime, multiplicity} <- [{3, 1}, {11, 2}, {10_177, 2}, {859_267, 2}, {52_437_899, 2}] do
      @prime prime
      @multiplicity multiplicity
      test "rejects a point of order #{prime}" do
        point = prime_order_point(@prime, div(@cofactor * @r, Integer.pow(@prime, @multiplicity)))

        assert Curve.on_curve?(point)
        assert multiply(point, @prime) == :infinity
        refute Curve.in_subgroup?(point)
      end
    end
  end

  describe "pairing check" do
    test "is bilinear: e(aP, bQ) · e(−abP, Q) = 1" do
      {g1, g2} = {Curve.g1_generator(), Curve.g2_generator()}
      a = 0x1234_5678_9ABC_DEF0_1122_3344
      b = @r - 0xFEDC_BA98_7654_3210

      a_p = Curve.msm([{g1, a}])
      b_q = Curve.msm([{g2, b}])
      ab_p = Curve.neg(Curve.msm([{g1, rem(a * b, @r)}]))

      assert Curve.pairing_check([{a_p, b_q}, {ab_p, g2}])
      refute Curve.pairing_check([{a_p, b_q}, {Curve.neg(Curve.msm([{g1, a * b + 1}])), g2}])
      refute Curve.pairing_check([{g1, g2}])
    end
  end

  # A point of order `prime`: project the first suitable point on E (x = 1,
  # 2, ...) onto its ℓ-part with `cofactor` = h·r/ℓ^e, then multiply by ℓ
  # while the result stays finite. That works whether the ℓ-part is cyclic or
  # Z/ℓ × Z/ℓ.
  defp prime_order_point(prime, cofactor) do
    Stream.iterate(1, &(&1 + 1))
    |> Stream.map(&Curve.g1_decompress(<<1::1, 0::2, &1::381>>))
    |> Stream.flat_map(fn
      {:ok, point} -> [multiply(point, cofactor)]
      :error -> []
    end)
    |> Enum.find(&(&1 != :infinity))
    |> Stream.iterate(&multiply(&1, prime))
    |> Enum.find(&(multiply(&1, prime) == :infinity))
  end

  # Double-and-add with `Curve.add/2`, for scalars that must not be reduced
  # mod r (`Curve.msm/1` reduces them).
  defp multiply(point, scalar) do
    scalar
    |> Integer.digits(2)
    |> Enum.reduce(:infinity, fn bit, acc ->
      acc = Curve.add(acc, acc)
      if bit == 1, do: Curve.add(acc, point), else: acc
    end)
  end
